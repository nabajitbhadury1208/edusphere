package com.cts.edusphere.enums;

/**
 * Defines the coverage scope or subject area of an institutional report.
 */
public enum ReportScope {
    /** The report covers metrics and data for a specific department. */
    DEPARTMENT,
    /** The report covers institution-wide metrics and operational data. */
    INSTITUTION,
    /** The report covers financial data, budgets, and fee-related metrics. */
    FINANCIAL,
    /** The report covers compliance evaluations and regulatory adherence. */
    COMPLIANCE,
    /** The report covers academic performance, grades, and curriculum data. */
    ACADEMIC,
    /** The report covers research project activity and outcomes. */
    RESEARCH
}
